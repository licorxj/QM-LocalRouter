"""Windows 开机自启动（用户级启动文件夹 + VBS 隐藏窗口）。

用一个 VBS 启动脚本放入当前用户的「启动」目录，登录 Windows 后由资源管理器
自动执行。VBS 通过 WScript.Shell 以隐藏窗口方式拉起后端 uvicorn 进程，从而
开机后自动提供 UI + API 服务，且不弹出黑色命令行窗口。

设计要点：
- 走「启动文件夹」而非注册表 HKCU Run：无需管理员权限，卸载/关闭只需删文件。
- 以「文件是否存在」作为唯一真实状态来源，不往 app_settings.json 写镜像字段，
  避免用户手动删除启动项后与本系统状态不一致。
- 非 Windows 平台优雅降级：status().supported=False，不报错。
"""
import os
import sys
from pathlib import Path

_APP_NAME = "ApiRouteManeger"
_VBS_NAME = "ApiRouteManeger.vbs"


def _startup_dir() -> Path | None:
    """当前用户的 Windows 启动文件夹；非 Windows / 环境异常返回 None。"""
    if os.name != "nt":
        return None
    appdata = os.environ.get("APPDATA")
    if not appdata:
        return None
    d = Path(appdata) / "Microsoft" / "Windows" / "Start Menu" / "Programs" / "Startup"
    try:
        d.mkdir(parents=True, exist_ok=True)
    except OSError:
        return None
    return d


def script_path() -> Path | None:
    d = _startup_dir()
    return (d / _VBS_NAME) if d else None


def is_supported() -> bool:
    return _startup_dir() is not None


def is_enabled() -> bool:
    p = script_path()
    return bool(p and p.is_file())


def _build_vbs() -> str:
    """生成 VBS：设置工作目录为 backend，隐藏窗口启动 uvicorn（API + 前端单进程）。"""
    from app.config import settings as app_config, BASE_DIR

    backend_dir = BASE_DIR  # backend/ 目录，uvicorn 的 WorkingDirectory
    python = sys.executable  # 当前正在运行后端的解释器，保证可用
    host = "0.0.0.0"  # 与 start-prod.bat 一致，开机后局域网也可访问
    port = app_config.PORT

    cmd = f'"{python}" -m uvicorn app.main:app --host {host} --port {port}'
    cmd_vbs = cmd.replace('"', '""')
    wdir_vbs = str(backend_dir).replace('"', '""')
    return (
        f"' {_APP_NAME} autostart - generated by app, do not edit\r\n"
        "On Error Resume Next\r\n"
        'Set WshShell = CreateObject("WScript.Shell")\r\n'
        f'WshShell.CurrentDirectory = "{wdir_vbs}"\r\n'
        f'WshShell.Run "{cmd_vbs}", 0, False\r\n'
    )


def enable() -> bool:
    p = script_path()
    if not p:
        return False
    try:
        p.write_text(_build_vbs(), encoding="utf-8")
        return True
    except OSError:
        return False


def disable() -> bool:
    p = script_path()
    if not p:
        return False
    try:
        if p.is_file():
            p.unlink()
        return True
    except OSError:
        return False


def status() -> dict:
    p = script_path()
    return {
        "enabled": is_enabled(),
        "supported": is_supported(),
        "script_path": str(p) if p else "",
    }
